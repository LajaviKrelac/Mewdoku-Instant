// UI batch (2026-10-13): levelbutton — writes src/game/level-tiers.ts, the shipped Extra-hard levels, from the packs.
// A Hard level is Extra hard when its own board is (game/ramp.ts isExtraHardBoard: grade 5, or grader effort ≥
// levels.extraHardMinEffort). The packs are fixed data, so the runtime keeps the answer as a short static list instead
// of loading a pack to label the Home button; tests/property/level-tiers.spec.ts re-reads the packs and fails when the
// list is stale. Re-run after a pack regeneration or a threshold change.
//
// Usage: npx tsx scripts/gen-level-tiers.ts [--data src/data] [--check]
//   --check: write nothing; exit 1 when the file on disk differs from what the packs give.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { cfg, type GameConfig } from '../src/app/config';
import type { LevelPack } from '../src/engine/types';
import { isExtraHardBoard, isHardLevel } from '../src/game/ramp';

export const LEVEL_TIERS_FILE = 'src/game/level-tiers.ts';

/** The level packs under `<dataDir>/levels`, in file order. */
export function readLevelPacks(dataDir: string): LevelPack[] {
  const dir = `${dataDir}/levels`;
  return readdirSync(dir)
    .filter((f) => /^pack-\d{3}\.json$/.test(f))
    .sort()
    .map((f) => JSON.parse(readFileSync(`${dir}/${f}`, 'utf8')) as LevelPack);
}

/** Every shipped Hard level whose record is an extra-hard board, ascending. */
export function extraHardLevelsOf(packs: readonly LevelPack[], c: GameConfig = cfg): number[] {
  const out: number[] = [];
  for (const pack of packs) {
    pack.levels.forEach((rec, q) => {
      const level = rec.i ?? pack.first + q;
      if (isHardLevel(level, c) && isExtraHardBoard({ grade: rec.g, effort: rec.e }, c)) out.push(level);
    });
  }
  return out.sort((a, b) => a - b);
}

/** The TypeScript module for `levels` (10 numbers per line). */
export function formatLevelTiers(levels: readonly number[], hardCount: number, c: GameConfig = cfg): string {
  const rows: string[] = [];
  for (let k = 0; k < levels.length; k += 10) rows.push(`  ${levels.slice(k, k + 10).join(', ')},`);
  return [
    '// UI batch (2026-10-13): levelbutton — GENERATED by scripts/gen-level-tiers.ts from src/data/levels/pack-*.json. Do not edit.',
    `// The shipped Hard levels whose own board is extra hard (game/ramp.ts isExtraHardBoard: grade 5, or grader effort ≥`,
    `// levels.extraHardMinEffort = ${c.levels.extraHardMinEffort}): ${levels.length} of ${hardCount}. tests/property/level-tiers.spec.ts re-reads the packs.`,
    '/** Ascending level numbers (all ≤ levels.shipped). */',
    'export const EXTRA_HARD_LEVELS: readonly number[] = Object.freeze([',
    ...rows,
    ']);',
    '',
  ].join('\n');
}

/** The file's text for the packs under `dataDir`. */
export function levelTiersSource(dataDir: string, c: GameConfig = cfg): string {
  const packs = readLevelPacks(dataDir);
  let hard = 0;
  for (const pack of packs) pack.levels.forEach((rec, q) => (hard += isHardLevel(rec.i ?? pack.first + q, c) ? 1 : 0));
  return formatLevelTiers(extraHardLevelsOf(packs, c), hard, c);
}

export function main(argv: readonly string[]): void {
  const at = argv.indexOf('--data');
  const dataDir = at >= 0 ? (argv[at + 1] ?? 'src/data') : 'src/data';
  const text = levelTiersSource(dataDir);
  if (argv.includes('--check')) {
    let old = '';
    try {
      old = readFileSync(LEVEL_TIERS_FILE, 'utf8');
    } catch {
      // missing: stale
    }
    const ok = old === text;
    process.stdout.write(`gen-level-tiers: ${LEVEL_TIERS_FILE} ${ok ? 'is current' : 'is STALE (run npx tsx scripts/gen-level-tiers.ts)'}\n`);
    if (!ok) process.exitCode = 1;
    return;
  }
  writeFileSync(LEVEL_TIERS_FILE, text);
  process.stdout.write(`gen-level-tiers: wrote ${LEVEL_TIERS_FILE}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
